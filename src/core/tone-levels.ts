export function toneLevel(value: number): ToneLevel {
  const index = Math.max(0, Math.min(11, Math.round(Number(value) || 0)));
  return TONE_LEVELS[index];
}

/** Кубик для шкалы: честные 12 граней. */
export function rollToneLevel(seedText?: string): number {
  if (!seedText) return Math.floor(Math.random() * 12);

  let hash = 2166136261;
  for (const char of seedText) {
    hash ^= char.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  hash = (hash + 0x6d2b79f5) >>> 0;
  hash = Math.imul(hash ^ (hash >>> 15), hash | 1);
  hash ^= hash + Math.imul(hash ^ (hash >>> 7), hash | 61);
  return ((hash ^ (hash >>> 14)) >>> 0) % 12;
}

/** Текст директивы для промта. Пустая строка, если уровень не задан. */
export function toneDirective(value: unknown): string {
  if (value === undefined || value === null || value === '') return '';
  const level = toneLevel(Number(value));
  return `# УРОВЕНЬ ИНТЕНСИВНОСТИ (${level.value}/11 — ${level.name})\n${level.directive}\nНе меняй жанр, мир, сеттинг или тему из-за этого уровня.`;
}
