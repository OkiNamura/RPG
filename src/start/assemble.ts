/**
 * Фаза A: сборка кампании по тегам.
 *
 * На старте игры мир и тон НЕ берутся из каталога — они генерируются
 * по тегам, которые выбрал игрок. Каталог миров (`Миры\V!`) — это
 * референсы и источник тегов, а не готовые кампании.
 *
 * Пока — заглушка: интерфейс зафиксирован, реализация в M2.
 * Заглушка нужна, чтобы весь цикл можно было прогнать целиком уже сейчас.
 */

import type { Model } from '../core/model.ts';
import { estimateTokens } from '../core/context.ts';

export interface StartTags {
  /** тип мира и его черты: «dark fantasy», «гнилая империя», «море»… */
  world: string[];
  /** настройки тона: «жёсткий», «медленный», «чёрный юмор»… */
  tone: string[];
  /** черты героя; промт героя появится позже */
  hero?: string[];
}

export interface CampaignBible {
  world: string;
  tone: string;
  hero: string;
  tokens: number;
  /** true, пока это заглушка, а не ответ моделей */
  stub: boolean;
}

export async function assembleCampaign(tags: StartTags, model: Model): Promise<CampaignBible> {
  // M2: здесь будут два независимых вызова —
  //   1) генератор мира  (структура: «Промт миры v6»)
  //   2) генератор тона  (структура: «Тон v1»)
  // и проверка, что тон не противоречит миру.
  void model;

  const world = [
    `# МИР (ЗАГЛУШКА, теги: ${tags.world.join(', ') || 'не заданы'})`,
    '',
    'Здесь должен быть развёрнутый мир: устройство, расы, фракции, экономика,',
    'история, стартовые NPC и локации, секреты, угрозы.',
  ].join('\n');

  const tone = [
    `# ТОН (ЗАГЛУШКА, теги: ${tags.tone.join(', ') || 'не заданы'})`,
    '',
    'Здесь должны быть настройки описания: лицо повествования, ритм, объём,',
    'уровень жёсткости, запреты, лексика.',
  ].join('\n');

  const hero = [
    '# ГЕРОЙ (ЗАГЛУШКА)',
    '',
    'Черты героя появятся позже отдельным промтом.',
  ].join('\n');

  return {
    world,
    tone,
    hero,
    tokens: estimateTokens(world) + estimateTokens(tone) + estimateTokens(hero),
    stub: true,
  };
}
