function countWords(text) {
  const matches = text.match(/[A-Za-zА-Яа-яЁё0-9]+(?:[-‑][A-Za-zА-Яа-яЁё0-9]+)*/g);
  return matches ? matches.length : 0;
}

const catalog = JSON.parse(readFileSync(CATALOG_PATH, 'utf8'));
const toneGroups = catalog?.tone?.groups;
if (!Array.isArray(toneGroups) || toneGroups.length === 0) {
  console.error('catalog.json: не найдена структура tone.groups');
  process.exit(1);
}

const tags = [];
let subgroupCount = 0;
for (const group of toneGroups) {
  for (const subgroup of group.subgroups ?? []) {
    subgroupCount += 1;
    for (const field of subgroup.fields ?? []) {
      tags.push({
        group: group.group,
        subgroup: subgroup.subgroup,
        name: field.name,
        catalogDescription: String(field.description ?? '').trim(),
      });
    }
  }
}

const knownKeys = new Set(tags.map((tag) => `${tag.group}: ${tag.name}`.toLowerCase()));
const extraKeys = [];
for (const [groupName, items] of Object.entries(DESC)) {
  for (const tagName of Object.keys(items)) {
    const key = `${groupName}: ${tagName}`.toLowerCase();
    if (!knownKeys.has(key)) extraKeys.push(key);
  }
}

const descriptions = {};
const missing = [];
const fromCatalog = [];
const tooShort = [];
const tooLong = [];
const duplicates = [];
const seenText = new Map();

for (const tag of tags) {
  const key = `${tag.group}: ${tag.name}`.toLowerCase();
  let text = DESC[tag.group]?.[tag.name];

  if (!text || !text.trim()) {
    if (tag.catalogDescription) {
      text = tag.catalogDescription;
      fromCatalog.push(key);
    } else {
      missing.push(key);
      continue;
    }
  }

  text = text.trim().replace(/\s+/gu, ' ');
  const words = countWords(text);
  if (words < MIN_WORDS) tooShort.push(`${key} (${words})`);
  if (words > MAX_WORDS) tooLong.push(`${key} (${words})`);

  const previous = seenText.get(text);
  if (previous) duplicates.push(`${key} == ${previous}`);
  else seenText.set(text, key);

  descriptions[key] = text;
}

const sorted = {};
for (const key of Object.keys(descriptions).sort((a, b) => a.localeCompare(b, 'ru'))) {
  sorted[key] = descriptions[key];
}

writeFileSync(OUT_PATH, `${JSON.stringify(sorted, null, 2)}\n`, 'utf8');

const covered = Object.keys(descriptions).length;
const total = tags.length;
console.log(`описаний: ${covered} из ${total}`);
console.log(
  `групп: ${toneGroups.length}, подгрупп: ${subgroupCount}, ` +
    `своих формулировок: ${covered - fromCatalog.length}, из каталога: ${fromCatalog.length}`,
);
console.log(`слов в диапазоне ${MIN_WORDS}–${MAX_WORDS}: ${covered - tooShort.length - tooLong.length}`);

let failed = false;
const report = (title, list) => {
  if (list.length === 0) return;
  failed = true;
  console.error(`\n${title} (${list.length}):`);
  for (const item of list.slice(0, 25)) console.error(`  - ${item}`);
  if (list.length > 25) console.error(`  ... и ещё ${list.length - 25}`);
};

report('НЕТ ОПИСАНИЯ', missing);
report('ЛИШНИЕ КЛЮЧИ (нет такого тега в каталоге)', extraKeys);
report('КОРОЧЕ 6 СЛОВ', tooShort);
report('ДЛИННЕЕ 16 СЛОВ', tooLong);
report('ПОВТОРЯЮЩИЕСЯ ОПИСАНИЯ', duplicates);

if (fromCatalog.length > 0) {
  console.error(`\nВНИМАНИЕ: взято из каталога, добавь свою формулировку (${fromCatalog.length}):`);
  for (const key of fromCatalog.slice(0, 25)) console.error(`  - ${key}`);
  failed = true;
}

if (covered !== total) {
  console.error(`\nПокрытие неполное: ${covered} из ${total}`);
  failed = true;
}

if (failed) process.exit(1);
console.log(`OK: ${OUT_PATH} записан, все ${total} тегов покрыты.`);
