function heroSubgroup(low) {
  const tail = low.replace(/^гг[\s-]*/u, '');
  for (const [rule, subgroup] of HERO_TAIL) {
    if (rule.test(tail)) return subgroup;
  }
  return 'ГГ: типаж';
}

const FALLBACK = {
  Жанры: 'Жанры',
  'Сеттинг и атмосфера': 'Прочее',
  'Персонажи и типажи': 'Типажи',
  'Элементы сюжета и тропы': 'Тропы',
  'Отношения и романтика': 'Романтика',
  'Контент-теги (18+ и зрелый контент)': 'Прочее',
  Формат: 'Тип контента',
};

function pickSubgroup(group, name) {
  const low = String(name).toLowerCase();
  if (group === 'Персонажи и типажи' && /^гг/u.test(low)) return heroSubgroup(low);
  for (const [rule, subgroup] of RULES[group] ?? []) {
    if (rule.test(low)) return subgroup;
  }
  return FALLBACK[group] ?? 'Прочее';
}

export function normalizeToneGroups(groups) {
  // 1. Переименование и слияние групп.
  const byGroup = new Map();
  for (const group of groups) {
    const target = GROUP_RENAME[group.group] ?? group.group;
    const list = byGroup.get(target) ?? [];
    for (const sg of group.subgroups) list.push(...sg.fields);
    byGroup.set(target, list);
  }

  // 2. Глобальная дедупликация: имя встречается один раз.
  const seen = new Map();
  const ordered = [];

  const orderedGroups = [...byGroup.keys()].sort((a, b) => {
    const ia = GROUP_ORDER.indexOf(a);
    const ib = GROUP_ORDER.indexOf(b);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib);
  });

  for (const groupName of orderedGroups) {
    const fields = byGroup.get(groupName) ?? [];
    for (const field of fields) {
      const k = key(field.name);
      const existing = seen.get(k);
      if (existing) {
        // Дубликат: сохраняем более длинное описание, тег остаётся в первой группе.
        if ((field.description ?? '').length > (existing.description ?? '').length) {
          existing.description = field.description;
        }
        continue;
      }
      seen.set(k, field);
      ordered.push({ group: groupName, field });
    }
  }

  // 3. Раскладка по подкатегориям и алфавиту.
  const result = new Map();
  for (const { group, field } of ordered) {
    const target = GROUP_RENAME[group] ?? group;
    const subgroups = result.get(target) ?? new Map();
    const bucket = pickSubgroup(target, field.name);
    const list = subgroups.get(bucket) ?? [];
    list.push(field);
    subgroups.set(bucket, list);
    result.set(target, subgroups);
  }

  const out = [];
  for (const groupName of orderedGroups) {
    const subgroups = result.get(groupName);
    if (!subgroups) continue;
    const list = [];
    for (const [subgroup, fields] of subgroups) {
      fields.sort((a, b) => a.name.localeCompare(b.name, 'ru'));
      list.push({ subgroup, fields });
    }
    out.push({ group: groupName, subgroups: list });
  }
  return out;
}
