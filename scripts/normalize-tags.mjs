/**
 * Нормализация тегов тона.
 *
 * Что делает:
 *  1. сводит одинаковые теги к одной записи (глобально, не внутри группы);
 *  2. сливает «Жанры (доп.)» в «Жанры», «Сеттинг» в «Сеттинг и атмосфера»;
 *  3. разбивает плоские списки на осмысленные подкатегории;
 *  4. убирает пустые подгруппы и раскладывает поля по алфавиту.
 *
 * Функция чистая: принимает группы из build-catalog и возвращает новые.
 */

/** Ключ для сравнения: регистр, лишние пробелы, хвостовая пунктуация. */
function key(name) {
  return name
    .normalize('NFC')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .replace(/[.!?…]+$/u, '')
    .trim();
}

