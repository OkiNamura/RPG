const ADULT_MARKERS = /(?:18\+|\bпорн|\bэрот|\bсекс)/iu;

function cleanText(value) {
  return String(value ?? '').replace(/\s+/g, ' ').trim();
}

/**
 * Ключ сравнения названий: NFC, нижний регистр, схлопнутые пробелы
 * и обрезанная хвостовая пунктуация. Внутренняя пунктуация значима,
 * поэтому «кадр 16:9» и «кадр 16 9» — разные теги.
 */
function nameKey(value) {
  return String(value ?? '')
    .normalize('NFC')
    .toLocaleLowerCase('ru-RU')
    .replace(/\s+/gu, ' ')
    .trim()
    .replace(/[^\p{L}\p{N}]+$/u, '')
    .trim();
}

function wordCount(value) {
  return value.split(' ').filter(Boolean).length;
}

function countSourceFields(source) {
  return source.reduce(
    (total, group) =>
      total + group.subgroups.reduce((sum, subgroup) => sum + subgroup.fields.length, 0),
    0,
  );
}

/**
 * Нормализует данные и удаляет повторы по всему каталогу.
 * Повтор внутри группы или между группами — это один и тот же тег;
 * остаётся первое вхождение по порядку источника. Опустевшие после
 * дедупликации подгруппы не попадают в результат.
 */
function buildCatalog(source) {
  const seen = new Map();
  const removed = [];
  let droppedSubgroups = 0;

  const groups = source.map((groupEntry) => {
    const group = cleanText(groupEntry.group);
    const subgroups = [];

    for (const subgroupEntry of groupEntry.subgroups) {
      const subgroup = cleanText(subgroupEntry.subgroup);
      const fields = [];

      for (const raw of subgroupEntry.fields) {
        if (!Array.isArray(raw) || raw.length !== 2) {
          throw new Error(`Поле должно быть парой [название, описание] в группе «${group}»`);
        }

        const name = cleanText(raw[0]);
        const description = cleanText(raw[1]);
        const key = nameKey(name);

        if (!key) throw new Error(`Пустое название в группе «${group}»`);
        if (/\r|\n/.test(raw[0]) || /\r|\n/.test(raw[1])) {
          throw new Error(`Многострочное поле «${name}»: описание должно быть в одну строку`);
        }
        if (seen.has(key)) {
          removed.push({ name, group, subgroup, keptIn: seen.get(key) });
          continue;
        }

        seen.set(key, `${group} / ${subgroup}`);
        fields.push({ name, description });
      }

      if (fields.length === 0) {
        droppedSubgroups += 1;
        continue;
      }

      subgroups.push({ subgroup, fields });
    }

    return { group, subgroups };
  });

  return { groups, removed, droppedSubgroups };
}

function validate(catalog) {
  const errors = [];
  const groupNames = new Set();
  const allNameKeys = new Map();
  let total = 0;
  let subgroupCount = 0;
  let duplicateCount = 0;

  if (!Array.isArray(catalog.groups) || catalog.groups.length === 0) {
    return {
      errors: ['В каталоге нет ни одной группы'],
      total,
      subgroupCount,
      groupCount: 0,
      duplicateCount,
    };
  }

  for (const group of catalog.groups) {
    if (!group.group) errors.push('Пустое название группы');
    if (groupNames.has(group.group)) errors.push(`Дубль группы: «${group.group}»`);
    groupNames.add(group.group);

    if (!Array.isArray(group.subgroups) || group.subgroups.length === 0) {
      errors.push(`В группе «${group.group}» нет подгрупп`);
      continue;
    }

    const subgroupNames = new Set();
    let groupTotal = 0;

    for (const subgroup of group.subgroups) {
      if (!subgroup.subgroup) errors.push(`Пустое название подгруппы в «${group.group}»`);
      if (subgroupNames.has(subgroup.subgroup)) {
        errors.push(`Дубль подгруппы «${subgroup.subgroup}» в группе «${group.group}»`);
      }
      subgroupNames.add(subgroup.subgroup);
      subgroupCount += 1;

      if (!Array.isArray(subgroup.fields) || subgroup.fields.length === 0) {
        errors.push(`Пустая подгруппа «${group.group} / ${subgroup.subgroup}»`);
        continue;
      }

      for (const field of subgroup.fields) {
        total += 1;
        groupTotal += 1;

        const name = cleanText(field.name);
        const description = cleanText(field.description);
        const key = nameKey(name);
        const words = wordCount(name);

        if (!key) {
          errors.push(`Пустое название в «${group.group} / ${subgroup.subgroup}»`);
          continue;
        }
        if (words < MIN_NAME_WORDS || words > MAX_NAME_WORDS) {
          errors.push(`«${name}»: ${words} слов(а), нужно ${MIN_NAME_WORDS}–${MAX_NAME_WORDS}`);
        }
        if (!description) {
          errors.push(`«${name}»: пустое описание`);
        } else if (description.length > MAX_DESCRIPTION_LENGTH) {
          errors.push(`«${name}»: описание длиннее ${MAX_DESCRIPTION_LENGTH} символов`);
        }
        if (allNameKeys.has(key)) {
          duplicateCount += 1;
          errors.push(`Дубль тега «${name}»: «${allNameKeys.get(key)}»`);
        } else {
          allNameKeys.set(key, name);
        }
        if (ADULT_MARKERS.test(`${name} ${description}`)) {
          errors.push(`«${name}»: недопустимый контент 18+`);
        }
      }
    }

    if (groupTotal === 0) errors.push(`В группе «${group.group}» нет тегов`);
  }

  for (const required of REQUIRED_GROUPS) {
    if (!groupNames.has(required)) errors.push(`Не хватает обязательной группы «${required}»`);
  }
  if (total < MIN_TAGS) errors.push(`Тегов ${total}, нужно минимум ${MIN_TAGS}`);

  return { errors, total, subgroupCount, groupCount: catalog.groups.length, duplicateCount };
}

function fail(errors) {
  console.error(`Проверка не пройдена: ${errors.length} ошибок`);
  for (const error of errors.slice(0, 60)) console.error(`  - ${error}`);
  if (errors.length > 60) console.error(`  … и ещё ${errors.length - 60}`);
  process.exitCode = 1;
}

