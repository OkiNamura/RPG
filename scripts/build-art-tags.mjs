function pruneCatalog(groups) {
  let pruned = 0;
  let dropped = 0;

  // «Вид сверху» переезжает в план и точку зрения, остальной ракурс уходит.
  let viewTop = null;

  for (const group of groups) {
    if (PRUNE_GROUPS.has(group.group)) {
      dropped += 1;
      pruned += group.subgroups.reduce((sum, sg) => sum + sg.fields.length, 0);
      group.subgroups = [];
      continue;
    }

    for (const sg of group.subgroups) {
      if (sg.subgroup === 'Ракурс') {
        viewTop = sg.fields.find((field) => field.name.toLowerCase() === 'вид сверху') ?? null;
      }
    }

    group.subgroups = group.subgroups.filter((sg) => {
      if (PRUNE_SUBGROUPS.has(sg.subgroup)) {
        dropped += 1;
        pruned += sg.fields.length;
        return false;
      }

      sg.fields = sg.fields.filter((field) => {
        if (PRUNE_NAMES.has(field.name.toLowerCase())) {
          pruned += 1;
          return false;
        }
        return true;
      });

      if (sg.fields.length === 0) {
        dropped += 1;
        return false;
      }
      return true;
    });
  }

  // Пустые группы после чистки не держим.
  for (let i = groups.length - 1; i >= 0; i -= 1) {
    if (groups[i].subgroups.length === 0) groups.splice(i, 1);
  }

  const cameraGroup = groups.find((group) => group.group === 'Камера и композиция');
  if (cameraGroup) {
    const plan = cameraGroup.subgroups.find((sg) => sg.subgroup === 'План');
    const pov = POV_SUBGROUP.fields.filter((field) => !PRUNE_NAMES.has(field.name.toLowerCase()));
    if (plan) {
      const names = new Set(plan.fields.map((field) => field.name));
      for (const field of pov) if (!names.has(field.name)) plan.fields.push(field);
      if (viewTop && !names.has(viewTop.name)) plan.fields.push(viewTop);
      plan.subgroup = 'План и точка зрения';
    } else {
      cameraGroup.subgroups.push({ subgroup: 'План и точка зрения', fields: pov });
      if (viewTop) cameraGroup.subgroups[0].fields.push(viewTop);
    }
  }

  return { pruned, dropped };
}

