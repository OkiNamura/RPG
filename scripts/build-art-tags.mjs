  try {
    const formatData = JSON.parse(await readFile(join(ROOT, 'data', 'format-tags.json'), 'utf8'));
    groups.push({
      group: 'Формат и визуал',
      subgroups: [{ subgroup: 'Формат и визуал', fields: formatData.fields }],
    });
  } catch {
    console.warn('data/format-tags.json не найден — формат не перенесён');
  }

  // Школы и течения: короткий список базовых стилей вместо сотни подвидов.
  const styleSub = groups
    .find((group) => group.group === 'Стиль')
    ?.subgroups.find((sg) => sg.subgroup === 'Школы и течения');
  if (styleSub) styleSub.fields = STYLE_SUBGROUP.map((field) => ({ ...field }));

