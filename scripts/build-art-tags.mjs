  if (initial.errors.length > 0) {
    fail(initial.errors);
    return;
  }

  // Каталог уже прошёл валидацию; счётчик — справочный.
  const _expectedTotal = initial.total;
  const payload = { groups };
  await writeFile(OUT_FILE, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');

  const written = JSON.parse(await readFile(OUT_FILE, 'utf8'));
  const check = validate(written);

  if (check.errors.length > 0) {
    fail(check.errors);
    return;
  }
  if (check.total !== initial.total || check.groupCount !== initial.groupCount) {
    fail([`После записи изменилось количество: было ${initial.total}, стало ${check.total}`]);
    return;
  }
  if (check.duplicateCount !== 0) {
    fail([`В каталоге осталось дублей: ${check.duplicateCount}`]);
    return;
  }

  console.log('файл: data/art-tags.json');
  console.log(`групп: ${check.groupCount}, подгрупп: ${check.subgroupCount}`);
  console.log(`тегов: ${check.total}`);
  console.log(`полей в источнике: ${sourceTotal}`);
